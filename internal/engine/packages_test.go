func BenchmarkEngineActiveDiscovery(b *testing.B) {
	// Compare the same operator workload through the old filesystem seam and the
	// production typed boundary. Executor stub measures discovery, not test runs.
	viperSet(map[string]any{configuration.RunDryRunKey: true})
	defer viperReset()
	root := writePackageFiles(b, map[string]string{"source.go": applicabilitySource})
	for _, typed := range []bool{false, true} {
		name := "syntax"
		if typed {
			name = "active-typed"
		}
		b.Run(name, func(b *testing.B) {
			b.ReportAllocs()
			for b.Loop() {
				var opts []engine.Option
				if !typed {
					opts = append(opts, engine.WithDirFs(fstest.MapFS{"source.go": {Data: []byte(applicabilitySource)}}))
				}
				e := engine.New(gomodule.GoModule{Name: "example.com/discovery", Root: root, CallingDir: "."}, engine.CodeData{}, &executionStub{}, opts...)
				results, err := e.Run(context.Background())
				if err != nil {
					b.Fatal(err)
				}
				b.ReportMetric(float64(len(results.Mutants)), "candidates/op")
			}
		})
	}
}

