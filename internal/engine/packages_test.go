	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, m := range results.Mutants {
		got = append(got, strings.Join([]string{m.Type().String(), strconv.Itoa(m.Position().Line)}, ":"))
	}
	sort.Strings(got)
