func TestEngineTypedApplicabilityGenericConstraints(t *testing.T) {
	viperSet(map[string]any{configuration.RunDryRunKey: true})
	defer viperReset()
	root := writePackageFiles(t, map[string]string{"source.go": `package sample
 type Text string
 type Strings interface { ~string }
 type Mixed interface { ~int | ~string }
 func named[T Text](a,b T) T { return a+b }
 func embedded[T Strings](a,b T) T { return a+b }
 func intersection[T interface { Mixed; ~int }](a,b T) T { return a+b }
 func arrays(a int) [1 | 2]int { return [1 | 2]int{} }
 `})
	e := engine.New(gomodule.GoModule{Name: "example.com/discovery", Root: root, CallingDir: "."}, engine.CodeData{}, newJobDealerStub(t))
	results, err := e.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	var arithmetic, bitwise int
	for _, m := range results.Mutants {
		switch {
		case m.Type() == mutator.ArithmeticBase:
			arithmetic++
			if m.Position().Line != 7 {
				t.Fatalf("unexpected arithmetic at %s", m.Position())
			}
		case m.Type() == mutator.InvertBitwise:
			bitwise++
		default:
			t.Fatalf("unexpected mutant %s", m.Type())
		}
	}
	if arithmetic != 1 || bitwise != 2 {
		t.Fatalf("arithmetic=%d bitwise=%d, want 1, 2", arithmetic, bitwise)
	}
}

func TestEngineActiveCgoOriginals(t *testing.T) {
	if _, err := exec.LookPath("gcc"); err != nil {
		t.Skip("cgo fixture needs gcc")
	}
	viperSet(map[string]any{configuration.RunDryRunKey: true})
	defer viperReset()
	var diagnostics bytes.Buffer
	log.Init(&diagnostics)
	t.Cleanup(log.Reset)
	t.Setenv("CGO_ENABLED", "1")
	t.Setenv("CC", "gcc")
	root := writePackageFiles(t, map[string]string{"cgo.go": "package sample\nimport \"C\"\nfunc Cgo(x int) int { return x + 1 }\n", "source.go": "package sample\nvar N = 1 + 2\n"})
	mod := gomodule.GoModule{Name: "example.com/discovery", Root: root, CallingDir: "."}
	e := engine.New(mod, engine.CodeData{}, newJobDealerStub(t))
	results, err := e.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if len(results.Mutants) != 2 {
		t.Fatalf("want original cgo and plain Go candidates, got %v", results.Mutants)
	}
	if !strings.Contains(diagnostics.String(), "type-based applicability checks unavailable") {
		t.Fatalf("missing cgo applicability diagnostic: %s", diagnostics.String())
	}

	for _, m := range results.Mutants {
		if m.Position().Filename == "cgo.go" {
			//nolint:gosec // Test-owned temporary module source.
			original, err := os.ReadFile(filepath.Join(root, "cgo.go"))
			if err != nil {
				t.Fatal(err)
			}
			if original[m.Position().Offset] != '+' {
				t.Fatalf("cgo position is not an original-source operator: %s", m.Position())
			}
		}
	}
	configuration.Set(configuration.RunExcludeFiles, []string{`^cgo\.go$`})
	rules, err := exclusion.New()
	if err != nil {
		t.Fatal(err)
	}
	e = engine.New(mod, engine.CodeData{Exclusion: rules}, newJobDealerStub(t))
	results, err = e.Run(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if len(results.Mutants) != 1 || results.Mutants[0].Position().Filename != "source.go" {
		t.Fatalf("want non-cgo target only, got %v", results.Mutants)
	}
}

func TestEngineActiveInternalTestBooleanShadows(t *testing.T) {
	viperSet(map[string]any{configuration.RunDryRunKey: true})
	defer viperReset()
	root := writePackageFiles(t, map[string]string{
		"use.go":                "package sample\nfunc f() bool { return false }\nfunc g() bool { return true }\n",
		"internal_test.go":      "//go:build shadow\n\npackage sample\nvar false = true\nvar testOnly = 1 + 2\n",
		"inactive_test.go":      "//go:build inactive\n\npackage sample\nvar true = false\n",
		"internal_true_test.go": "//go:build shadowtrue\n\npackage sample\nvar true = false\n",
		"external_test.go":      "package sample_test\nvar true = false\nvar false = true\nvar testOnly = 2 + 3\n",
	})
	for _, tags := range []string{"", "shadow", "shadowtrue"} {
		t.Run("tags="+tags, func(t *testing.T) {
			configuration.Set(configuration.RunTagsKey, tags)
			e := engine.New(gomodule.GoModule{Name: "example.com/discovery", Root: root, CallingDir: "."}, engine.CodeData{}, newJobDealerStub(t))
			results, err := e.Run(context.Background())
			if err != nil {
				t.Fatal(err)
			}
			var lines []int
			for _, m := range results.Mutants {
				if m.Position().Filename != "use.go" || m.Type() != mutator.BooleanLiteral {
					t.Fatalf("test file became a target: %s %s", m.Position(), m.Type())
				}
				lines = append(lines, m.Position().Line)
			}
			sort.Ints(lines)
			want := []int{2, 3}
			switch tags {
			case "shadow":
				want = []int{3}
			case "shadowtrue":
				want = []int{2}
			}
			if !reflect.DeepEqual(lines, want) {
				t.Fatalf("Boolean mutation lines=%v, want %v", lines, want)
			}
		})
	}
}

