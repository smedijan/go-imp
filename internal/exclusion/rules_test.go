package exclusion_test

import (
	"testing"

	"github.com/smedijan/go-imp/internal/configuration"
	"github.com/smedijan/go-imp/internal/exclusion"
)

func TestRules_IsFileExcluded(t *testing.T) {
	generated := []byte("// Code generated by tool. DO NOT EDIT.\npackage example\n")
	ordinary := []byte("package example\n")

	t.Run("generated files excluded by default", func(t *testing.T) {
		configuration.Set(configuration.RunExcludeFiles, []string(nil))
		configuration.Set(configuration.RunIncludeFiles, []string(nil))
		rules, err := exclusion.New()
		if err != nil {
			t.Fatal(err)
		}
		if !rules.IsFileExcluded("generated.go", generated) {
			t.Fatal("generated file should be excluded")
		}
		if rules.IsFileExcluded("source.go", ordinary) {
			t.Fatal("ordinary file should not be excluded")
		}
	})

	t.Run("explicit include overrides generated detection", func(t *testing.T) {
		configuration.Set(configuration.RunExcludeFiles, []string(nil))
		configuration.Set(configuration.RunIncludeFiles, []string{"generated\\.go$"})
		rules, err := exclusion.New()
		if err != nil {
			t.Fatal(err)
		}
		if rules.IsFileExcluded("generated.go", generated) {
			t.Fatal("explicitly included generated file should not be excluded")
		}
	})

	t.Run("explicit exclude overrides include", func(t *testing.T) {
		configuration.Set(configuration.RunExcludeFiles, []string{"generated\\.go$"})
		configuration.Set(configuration.RunIncludeFiles, []string{"generated\\.go$"})
		rules, err := exclusion.New()
		if err != nil {
			t.Fatal(err)
		}
		if !rules.IsFileExcluded("generated.go", ordinary) {
			t.Fatal("explicit exclusion should take precedence")
		}
	})

	t.Run("invalid regular expression", func(t *testing.T) {
		configuration.Set(configuration.RunExcludeFiles, []string{"["})
		configuration.Set(configuration.RunIncludeFiles, []string(nil))
		if _, err := exclusion.New(); err == nil {
			t.Fatal("expected an error")
		}
	})
}

func TestIsGenerated(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{name: "standard marker", src: "// Code generated by tool. DO NOT EDIT.\npackage p\n", want: true},
		{name: "different case", src: "// code generated by tool. DO NOT EDIT.\npackage p\n"},
		{name: "missing period", src: "// Code generated by tool. DO NOT EDIT\npackage p\n"},
		{name: "ordinary comment", src: "// Generated by tool.\npackage p\n"},
		{name: "marker-like text in block comment", src: "/*\n// Code generated by tool. DO NOT EDIT.\n*/\npackage p\n"},
		{name: "marker after package", src: "package p\n// Code generated by tool. DO NOT EDIT.\n"},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := exclusion.IsGenerated([]byte(tc.src)); got != tc.want {
				t.Errorf("IsGenerated() = %t, want %t", got, tc.want)
			}
		})
	}
}
